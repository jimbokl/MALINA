export const observationSources = {
  general: {
    label: 'Penn State Extension: осмотр признаков болезней клубники',
    url: 'https://extension.psu.edu/strawberry-disease-identification'
  },
  strawberryRoots: {
    label: 'Penn State Extension: корни и сердечко клубники',
    url: 'https://extension.psu.edu/crown-and-root-issues-in-strawberries'
  },
  raspberryRoots: {
    label: 'Penn State Extension: корневая гниль малины',
    url: 'https://extension.psu.edu/raspberry-disease-phytophthora-root-rot'
  },
  raspberryLeaves: {
    label: 'University of Minnesota Extension: изменения окраски листьев малины',
    url: 'https://apps.extension.umn.edu/garden/diagnose/plant/fruit/raspberry/leavesdiscolored.html'
  },
  herbicide: {
    label: 'University of Minnesota Extension: повреждения гербицидами',
    url: 'https://extension.umn.edu/garden-and-home/yard-and-garden/gardening-in-minnesota/herbicide-injury-on-garden-plants'
  },
  soil: {
    label: 'Penn State Extension: анализ почвы',
    url: 'https://extension.psu.edu/soil-testing'
  }
};

const valid = {
  crop: ['raspberry', 'strawberry'],
  symptom: ['yellow', 'wilt'],
  moisture: ['unknown', 'dry', 'wet', 'normal'],
  pattern: ['unknown', 'even', 'veins', 'spots'],
  spread: ['single', 'patch', 'many']
};

export function evaluateObservation(input) {
  for (const [key, values] of Object.entries(valid)) {
    if (!values.includes(input?.[key])) throw new Error(`Неизвестное значение поля ${key}`);
  }
  const roots = input.crop === 'raspberry' ? 'raspberryRoots' : 'strawberryRoots';
  const baseSteps = [
    'Сфотографируйте целое растение, поражённые листья с обеих сторон и соседние здоровые растения. Запишите, когда появились изменения и что происходило с поливом, погодой и обработками.',
    'Сравните поражённые растения со здоровыми рядом. Отметьте, проблема единичная, образует пятно или затронула всю посадку.'
  ];
  let title;
  let summary;
  let steps;
  let possibilities;
  let sources;

  if (input.symptom === 'wilt') {
    title = 'Начните с почвы и корней';
    sources = input.crop === 'raspberry' ? [roots, 'raspberryLeaves'] : [roots, 'general'];
    possibilities = 'Увядание бывает при нехватке воды, переувлажнении, повреждении корней и болезнях. Один внешний признак не различает эти причины.';
    if (input.moisture === 'wet') {
      summary = 'Почва мокрая, поэтому добавлять воду по одному виду листьев не стоит.';
      steps = [
        'Проверьте, застаивается ли вода и совпадают ли поражённые растения с понижениями участка. Не усиливайте полив, пока причина не ясна.',
        'Если растение продолжает увядать, осторожно осмотрите корни и основание ещё живого поражённого растения рядом со здоровым. При потемнении или разрушении тканей покажите образец местному специалисту.'
      ];
    } else if (input.moisture === 'dry') {
      summary = 'Сначала проверьте сухость почвы в зоне корней, а затем наблюдайте за растением после коррекции полива.';
      steps = [
        'Проверьте влажность грунта ниже поверхности рядом с корнями, а не только сухую корку сверху. Полив подбирайте по фактической влажности и дренажу участка.',
        'Если почва стала влажной, а увядание сохраняется или распространяется, проверьте корни и основание растения и обратитесь к специалисту.'
      ];
    } else if (input.moisture === 'normal') {
      summary = 'Почва влажная без застоя; одного полива как объяснения увядания недостаточно.';
      steps = [
        'Сравните корни и основание ещё живого поражённого растения со здоровым рядом. Отметьте повреждённые ткани и состояние молодых побегов.',
        'Если растение продолжает увядать, покажите фотографии и образец местному специалисту: причины могут различаться даже при нормальной влажности.'
      ];
    } else {
      summary = 'Влажность ещё не определена; без неё нельзя отличить часть причин увядания.';
      steps = [
        'Проверьте влажность почвы в зоне корней и наличие застоя воды. Сравните поражённое место с соседним здоровым участком.',
        'Если влага достаточная, а растение продолжает увядать, осмотрите корни и основание ещё живого поражённого растения; при повреждении тканей нужен местный специалист.'
      ];
    }
  } else if (input.pattern === 'veins') {
    title = 'Проверьте, где начинается пожелтение';
    summary = 'Жёлтая ткань при более зелёных жилках не доказывает дефицит железа.';
    possibilities = 'Питание растения, состояние корней и недавнее воздействие гербицидов могут давать похожую окраску.';
    steps = [
      'Отметьте, желтеют сначала молодые или старые листья. Сравните несколько растений и проверьте, не было ли сноса гербицида поблизости.',
      'Проверьте влажность и состояние корней. Перед внесением удобрений закажите анализ почвы; по одной фотографии дозу не определить.'
    ];
    sources = ['herbicide', input.crop === 'raspberry' ? 'raspberryLeaves' : 'general', 'soil'];
  } else if (input.pattern === 'spots') {
    title = 'Ищите дополнительные признаки';
    summary = 'Пятна или точечное пожелтение требуют осмотра листа с обеих сторон.';
    possibilities = 'Причиной могут быть вредители, инфекция или неинфекционное повреждение; цвет пятна сам по себе не устанавливает возбудителя.';
    steps = [
      'Осмотрите обратную сторону нескольких поражённых и здоровых листьев: есть ли насекомые, паутинка, налёт или спороношение. Сделайте крупные фотографии.',
      'Отметьте, на каких листьях и растениях пятна появились первыми. Если повреждение нарастает, передайте фотографии и образец местному специалисту, прежде чем выбирать обработку.'
    ];
    sources = input.crop === 'raspberry' ? ['raspberryLeaves', 'herbicide'] : ['general', 'herbicide'];
  } else {
    title = 'Сравните листья, почву и историю ухода';
    summary = 'Равномерное или пока неясное пожелтение имеет несколько возможных причин.';
    possibilities = 'Недостаток или избыток влаги, нарушение питания, повреждение корней и внешнее воздействие могут выглядеть сходно.';
    steps = [
      'Отметьте возраст первых пожелтевших листьев, влажность грунта в зоне корней и недавние подкормки или обработки.',
      'Если изменение охватывает посадку, проверьте почву перед новой подкормкой. Если растения вянут или есть повреждение корней, покажите образец специалисту.'
    ];
    sources = ['soil', 'herbicide', input.crop === 'raspberry' ? 'raspberryLeaves' : 'general'];
  }

  if (input.spread === 'many') {
    steps.unshift('Проблема затронула много растений: отметьте границы участка и общие факторы — воду, погоду, почву и недавние обработки. При быстром ухудшении нужна очная проверка.');
  }
  return {
    title, summary, possibilities,
    steps: [...baseSteps, ...steps],
    sources: [...new Set(sources)].map(key => observationSources[key]),
    limitation: 'При быстром ухудшении покажите фотографии и образец местному специалисту.'
  };
}
