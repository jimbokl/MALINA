export function pruningAdvice({ type, harvest }) {
  if (type === 'unknown') return answers.unknown;
  if (type === 'summer') return answers.summer;
  if (type === 'primocane') {
    if (harvest === 'single') return answers.single;
    if (harvest === 'double') return answers.double;
    return answers.unknown;
  }
  throw new RangeError('Выберите подтверждённый тип малины или вариант «Не знаю».');
}
